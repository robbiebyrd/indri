// Sanitize removes private items so a keyframe never exposes private data.
// It matches events.SanitizeDelta, so keyframes and deltas agree on visibility.
func (gs *Service) Sanitize(game *models.Game) *models.Game {
	game.PrivateData = nil
	game.Stage.PrivateData = nil

	for i, g := range game.Stage.Scenes {
		g.PrivateData = nil
		game.Stage.Scenes[i] = g
	}

	for i, t := range game.Teams {
		t.PrivateData = nil
		game.Teams[i] = t
	}

	for i, p := range game.Players {
		p.PrivateData = nil
		game.Players[i] = p
	}

	return game
}

// slimKeyframe returns a sanitized, layout-stripped copy of the game. Its schema
// version is the layout hash, which stays the same for the life of the game.
func (gs *Service) slimKeyframe(g *models.Game, layoutHash string) (events.KeyframeWrapper, error) {
	raw, err := json.Marshal(g)
	if err != nil {
		return events.KeyframeWrapper{}, err
	}
	var clone models.Game
	if err := json.Unmarshal(raw, &clone); err != nil {
		return events.KeyframeWrapper{}, err
	}
	slim := gs.Sanitize(&clone)
	if slim.PublicData != nil {
		delete(slim.PublicData, "layout")
	}
	return events.KeyframeWrapper{SV: layoutHash, Game: slim}, nil
}

// WriteKeyframe sends a LayoutFrame followed by a slim keyframe to a single connection.
func (gs *Service) WriteKeyframe(conn transport.Conn, g *models.Game, layoutHash string, layoutData map[string]interface{}) error {
	layoutFrame := events.LayoutFrame{O: events.OpLayout, V: layoutHash, Data: layoutData}
	if err := transport.WriteEncoded(conn, layoutFrame); err != nil {
		return err
	}
	wrapper, err := gs.slimKeyframe(g, layoutHash)
	if err != nil {
		return err
	}
	return transport.WriteEncoded(conn, wrapper)
}

// WriteSlimKeyframe sends a slim keyframe without a layout frame — used for refresh.
func (gs *Service) WriteSlimKeyframe(conn transport.Conn, g *models.Game, layoutHash string) error {
	wrapper, err := gs.slimKeyframe(g, layoutHash)
	if err != nil {
		return err
	}
	return transport.WriteEncoded(conn, wrapper)
}

