type Service struct {
	gameRepo gameRepo.Storer
	Script   *models.Script
}

// NewService creates a new repository for accessing game data.
func NewService(gameRepo gameRepo.Storer, scriptRepo *scriptRepo.Store) (*Service, error) {
	if gameRepo == nil {
		return nil, errors.New("the game service did not receive a game repo")
	}

	return &Service{
		gameRepo: gameRepo,
		Script:   scriptRepo.Get(),
	}, nil
}

// New creates a new game, with or without a Code.
func (gs *Service) New(gameCode string, private bool) (*models.Game, error) {
	if gameCode == "" {
		// If no gameCode was given, then we will try to create a random one
		autogenCode, err := gs.getAutoGeneratedGameCode()
		if err != nil {
			return nil, err
		}

		gameCode = autogenCode
	}

	if gs.Exists(gameCode) {
		return nil, fmt.Errorf("game with id %s already exists", gameCode)
	}

	log.Printf("creating new game with gameCode %v ", gameCode)

	g, err := gs.gameRepo.New(gameCode, gs.Script, private)
	if err != nil {
		return nil, err
	}

	return g, nil
}

// Get will fetch game data for a specific game ID.
func (gs *Service) Get(id string) (*models.Game, error) {
	g, err := gs.gameRepo.Get(id)
	if err != nil {
		return nil, fmt.Errorf("fetching game %q: %w", id, err)
	}

	return g, nil
}

// GetJSONBytes will fetch game data and return JSON bytes. It will create a game if it doesn't exist.
func (gs *Service) GetJSONBytes(id string) (*[]byte, error) {
	g, err := gs.Get(id)
	if err != nil {
		return nil, err
	}

	gameJSONBytes, err := json.Marshal(gs.Sanitize(g))
	if err != nil {
		return nil, err
	}

	return &gameJSONBytes, nil
}

// GetByCode will fetch game data for a specific game code.
func (gs *Service) GetByCode(gameCode string) (*models.Game, error) {
	if gameCode == "" {
		return nil, fmt.Errorf("game code is empty")
	}

	gameId, err := gs.gameRepo.GetIDHex(gameCode)
	if err != nil {
		return nil, fmt.Errorf("resolving game code %q: %w", gameCode, err)
	}

	g, err := gs.gameRepo.Get(*gameId)
	if err != nil {
		return nil, fmt.Errorf("fetching game %q: %w", gameCode, err)
	}

	return g, nil
}

// Fetch retrieves game data for a specific game ID and returns an error if not found.
func (gs *Service) Fetch(id string) (*models.Game, error) {
	if id == "" {
		return nil, fmt.Errorf("id is  nil")
	}

	return gs.gameRepo.Get(id)
}

